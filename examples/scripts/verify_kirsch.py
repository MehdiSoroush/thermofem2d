"""Reproduce exact-exterior Kirsch verification and finite-plate tension studies.

CSV values and figures are generated by the solver, not copied from reference
stress-concentration charts. Finite-plate stresses are not Kirsch exact data.
"""
from pathlib import Path
import csv
import json

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import numpy as np

from thermofem2d.circular_geometry import make_circular_mesh
from thermofem2d.curved_field import circular_field_mesh
from thermofem2d.kirsch import (
    canonical_first_quadrant_angle, hole_edge_stress_samples, kirsch_displacement,
    solve_finite_plate_uniform_tension, solve_kirsch_outer_dirichlet,
)

ROOT=Path(__file__).resolve().parents[2]
RADIUS=.25   # m
SIGMA=10e6  # Pa; gross-section applied remote traction


def mesh_for(kind, n, width=2.):
    return circular_field_mesh(make_circular_mesh(
        width=width,height=width,hole_radius=RADIUS,
        element_type=kind, per_side=n,radial=n))


def outer_exact_benchmark(mat,kind,n):
    mesh=mesh_for(kind,n)
    displacement=solve_kirsch_outer_dirichlet(mesh,mat,RADIUS,SIGMA)
    exact=kirsch_displacement(mesh.nodes,RADIUS,SIGMA,mat['E'],mat['nu']).reshape(-1)
    edge=hole_edge_stress_samples(mesh,mat,displacement)
    expected=1-2*np.cos(2*edge.theta_rad)
    normalized=edge.sigma_tt_pa/SIGMA
    return dict(kind=kind,subdivisions=n,nodes=len(mesh.nodes),elements=len(mesh.elements),
                displacement_relative_l2=float(np.linalg.norm(displacement-exact)/np.linalg.norm(exact)),
                hoop_rms_error_over_applied_stress=float(np.sqrt(np.mean((normalized-expected)**2))),
                max_sampled_sigma_theta_over_applied=float(np.max(normalized)),
                max_exact_at_sample_angles_over_applied=float(np.max(expected)),
                hole_radial_rms_over_applied=float(np.sqrt(np.mean((edge.sigma_rr_pa/SIGMA)**2))),
                max_quadratic_boundary_radius_error_m=float(np.max(np.abs(edge.radius_m-RADIUS))))


def finite_plate_benchmark(mat,n,width):
    mesh=mesh_for('T6',n,width)
    u=solve_finite_plate_uniform_tension(mesh,mat,SIGMA)
    edge=hole_edge_stress_samples(mesh,mat,u)
    kgross=float(np.max(edge.sigma_tt_pa)/SIGMA)
    # The net cross section perpendicular to the x load has height H-2a;
    # gross sigma=F/(Hh), net sigma=F/((H-2a)h).
    net_ratio=(width-2*RADIUS)/width
    return dict(width_m=width, hole_diameter_over_width=2*RADIUS/width,
                subdivisions=n,nodes=len(mesh.nodes),elements=len(mesh.elements),
                Kt_gross=kgross,Kt_net=kgross*net_ratio,
                peak_angle_first_quadrant_deg=canonical_first_quadrant_angle(
                    edge.theta_rad[np.argmax(edge.sigma_tt_pa)]),
                hole_radial_rms_over_applied=float(np.sqrt(np.mean((edge.sigma_rr_pa/SIGMA)**2))))


def _csv(path,records):
    # Explicit LF avoids platform-dependent CRLF on Windows.
    with path.open('w',newline='',encoding='utf-8') as handle:
        writer=csv.DictWriter(handle,fieldnames=list(records[0]),lineterminator='\n')
        writer.writeheader();writer.writerows(records)


def evaluate(output=ROOT/'results/verification'):
    output=Path(output);output.mkdir(parents=True,exist_ok=True)
    mat=json.loads((ROOT/'examples/steady_plate.json').read_text(encoding='utf-8'))['material']
    exact=[outer_exact_benchmark(mat,kind,n)
           for kind in ('T3','T6') for n in (3,4,6,8,10,12)]
    _csv(output/'kirsch_exact_boundary_convergence.csv',exact)
    finite=[finite_plate_benchmark(mat,n,width)
            for width,levels in ((2.,(4,6,8,10,12)),(4.,(8,12,16)))
            for n in levels]
    _csv(output/'kirsch_finite_plate_convergence.csv',finite)

    plt.rcParams.update({'font.size':10})
    fig,axes=plt.subplots(1,2,figsize=(11.6,4.4))
    for kind,color,marker in (('T3','#6a7d7c','s'),('T6','#007f75','o')):
        dat=[v for v in exact if v['kind']==kind]
        axes[0].loglog([v['subdivisions'] for v in dat],
                       [v['hoop_rms_error_over_applied_stress'] for v in dat],
                       marker=marker,color=color,label=kind,linewidth=2)
        axes[1].plot([v['subdivisions'] for v in dat],
                     [v['max_sampled_sigma_theta_over_applied'] for v in dat],
                     marker=marker,color=color,label=f'{kind}, exact outer BC')
    for width,style,color in ((2.,'--','#bc6a3c'),(4.,':','#6d6ca6')):
        data=[v for v in finite if v['width_m']==width]
        axes[1].plot([v['subdivisions'] for v in data],[v['Kt_gross'] for v in data],
                     linestyle=style,marker='^',color=color,label=f'T6, finite W={width:g} m')
    axes[1].axhline(3,color='#343a40',linestyle='-.',label='Kirsch infinite plane: 3')
    axes[0].set(xlabel='Subdivisions per plate side / radial direction',
                ylabel=r'Hole-edge hoop RMS error / $\sigma_\infty$',
                title='Analytical-boundary stress convergence')
    axes[1].set(xlabel='Subdivisions per plate side / radial direction',
                ylabel=r'Sampled peak hoop stress / $\sigma_\infty$',
                title='Distinct boundary-value problems')
    for ax in axes:
        ax.grid(alpha=.25,which='both');ax.legend(fontsize=8)
    fig.tight_layout();fig.savefig(output/'kirsch_stress_convergence.png',dpi=175)
    plt.close(fig)

    mesh=mesh_for('T6',12)
    ex=hole_edge_stress_samples(mesh,mat,
        solve_kirsch_outer_dirichlet(mesh,mat,RADIUS,SIGMA))
    fi=hole_edge_stress_samples(mesh,mat,
        solve_finite_plate_uniform_tension(mesh,mat,SIGMA))
    t=np.linspace(0,2*np.pi,361)
    fig,ax=plt.subplots(figsize=(8.4,4.8))
    ax.plot(np.rad2deg(t),1-2*np.cos(2*t),color='#242f32',
            label='Kirsch analytical hole surface',linewidth=2.2)
    ax.plot(np.rad2deg(ex.theta_rad),ex.sigma_tt_pa/SIGMA,'o',markersize=4,
            color='#007f75',label='T6: exact exterior displacements')
    ax.plot(np.rad2deg(fi.theta_rad),fi.sigma_tt_pa/SIGMA,'s',markersize=3.5,
            color='#bc6a3c',label='T6: finite 2 m plate, uniform tractions')
    ax.set(xlabel='Angle from applied x tension (degrees)',
           ylabel=r'Hole-edge hoop stress / $\sigma_\infty$',
           title='One-sided T6 edge-midpoint stress (n=12)',xlim=(0,360))
    ax.grid(alpha=.25);ax.legend(fontsize=9)
    fig.tight_layout();fig.savefig(output/'kirsch_hole_angular_stress.png',dpi=175)
    plt.close(fig)
    print('Analytical-exterior Kirsch checks:')
    for v in exact:
        print(f"  {v['kind']} n={v['subdivisions']:2d}: K_sample={v['max_sampled_sigma_theta_over_applied']:.5f}, "
              f"hoop_rms={v['hoop_rms_error_over_applied_stress']:.5f}, "
              f"relative_displacement_L2={v['displacement_relative_l2']:.3e}")
    print('Finite uniform-traction plate checks (gross and net normalization):')
    for v in finite:
        print(f"  W={v['width_m']:g} m, n={v['subdivisions']:2d}: "
              f"Kt_gross={v['Kt_gross']:.5f}, Kt_net={v['Kt_net']:.5f}")
    return exact,finite


if __name__=='__main__':
    evaluate()
